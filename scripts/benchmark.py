"""Room-sensing benchmark: score a submission against the no-audio baseline (plan 10.10).

The benchmark is the v2 held-out archive: 500 rooms × 8 poses, 64² grid,
p = 0 obstacles, a stereo pair 12 cells apart, and a known chirp. It is
regenerated byte-identically from ``data/MANIFEST.json`` (see
``docs/benchmark.md``). The training archive and its seeds are public on
the same terms. Tune only on training rooms.

A submission is an ``.npz`` file with

* ``prob``: float array ``(500, 64, 64)``, the obstacle probability per
  held-out room, in the archive's room order;
* ``threshold``: scalar, the operating point for IoU and boundary F,
  chosen on training rooms (optional; default 0.5);
* ``poses``: int, how many poses per room the method used (optional;
  recorded in the report).

Every method is compared with the no-audio baseline: the per-pixel prior
map of the training rooms, thresholded at the value that maximises the
mean training IoU. The comparison is the per-room paired difference
(mean ± SE, and z = mean / SE). The metrics are:

* IoU and boundary F (1-cell tolerance) at the submission's threshold;
* average precision, which is threshold-free;
* information gain in bits per room over the prior, which is proper, so
  it rewards calibrated probabilities and punishes over-confidence.

Usage::

    uv run python scripts/benchmark.py baseline --out prior.npz   # the no-audio submission
    uv run python scripts/benchmark.py score my_method.npz [--json out.json]
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import h5py
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from acoustic_system.learning.metrics import (  # noqa: E402
    average_precision,
    boundary_f,
    info_gain_bits,
    iou,
    mean_se,
    paired_diff_se,
)

TRAIN = ROOT / "data/training_data/active_sensing_v2_train_10kx4.hdf5"
HELDOUT = ROOT / "data/training_data/active_sensing_v2_heldout_500x8.hdf5"


def read_masks(path: pathlib.Path, limit: int | None = None) -> np.ndarray:
    with h5py.File(path, "r") as f:
        keys = sorted(k for k in f if k.startswith("sample_"))[:limit]
        return np.stack([np.asarray(f[k]["obstacles"]) > 0 for k in keys])


def prior_baseline(train: pathlib.Path, n_tau: int = 1000) -> tuple[np.ndarray, float]:
    """Per-pixel training prior and its training-optimal IoU threshold."""
    masks = read_masks(train)
    prior = masks.mean(axis=0)
    sample = masks[:n_tau]
    best, best_tau = -1.0, 0.5
    for tau in np.linspace(0.01, 0.5, 50):
        score = float(np.mean([iou(prior > tau, m) for m in sample]))
        if score > best:
            best, best_tau = score, float(tau)
    return prior.astype(np.float32), best_tau


def per_room(
    prob: np.ndarray, tau: float, truths: np.ndarray, prior: np.ndarray
) -> dict[str, list[float]]:
    out: dict[str, list[float]] = {"iou": [], "ap": [], "bf": [], "info_bits": []}
    for q, y in zip(prob, truths):
        out["iou"].append(iou(q > tau, y))
        out["ap"].append(average_precision(q, y))
        out["bf"].append(boundary_f(q > tau, y)[2])
        out["info_bits"].append(info_gain_bits(q, y, prior))
    return out


def score(sub: pathlib.Path, train: pathlib.Path, heldout: pathlib.Path) -> dict:
    data = np.load(sub)
    prob = np.asarray(data["prob"], dtype=np.float64)
    tau = float(data["threshold"]) if "threshold" in data else 0.5
    truths = read_masks(heldout)
    if prob.shape != truths.shape:
        raise SystemExit(f"prob has shape {prob.shape}, expected {truths.shape}")
    if not np.all((prob >= 0) & (prob <= 1)):
        raise SystemExit("prob must be probabilities in [0, 1]")
    prior, prior_tau = prior_baseline(train)
    # Score both in float64 (a float32 map compared with a float64 threshold
    # would flip pixels sitting exactly at the threshold).
    prior64 = prior.astype(np.float64)
    base = per_room(np.broadcast_to(prior64, truths.shape), prior_tau, truths, prior64)
    mine = per_room(prob, tau, truths, prior)
    res: dict = {
        "submission": sub.name,
        "rooms": int(len(truths)),
        "poses": int(data["poses"]) if "poses" in data else None,
        "threshold": tau,
        "baseline_threshold": prior_tau,
        "metrics": {},
    }
    for k in ("iou", "ap", "bf", "info_bits"):
        m, se = mean_se(mine[k])
        bm, bse = mean_se(base[k])
        d, dse = paired_diff_se(mine[k], base[k])
        res["metrics"][k] = {
            "mean": m,
            "se": se,
            "baseline": bm,
            "baseline_se": bse,
            "delta": d,
            "delta_se": dse,
            "z": d / dse if dse and dse > 0 else float("nan"),
        }
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    b = sp.add_parser("baseline", help="write the no-audio baseline as a submission")
    b.add_argument("--out", type=pathlib.Path, default=pathlib.Path("prior_baseline.npz"))
    s = sp.add_parser("score", help="score a submission .npz")
    s.add_argument("submission", type=pathlib.Path)
    s.add_argument("--json", type=pathlib.Path, default=None)
    for p in (b, s):
        p.add_argument("--train", type=pathlib.Path, default=TRAIN)
        p.add_argument("--heldout", type=pathlib.Path, default=HELDOUT)
    args = ap.parse_args(argv)
    if args.cmd == "baseline":
        prior, tau = prior_baseline(args.train)
        n = len(read_masks(args.heldout))
        np.savez_compressed(
            args.out, prob=np.broadcast_to(prior, (n, *prior.shape)), threshold=tau, poses=0
        )
        print(f"wrote {args.out} (prior map, threshold {tau:.2f})")
        return 0
    res = score(args.submission, args.train, args.heldout)
    names = {"iou": "IoU", "ap": "AP", "bf": "boundary F", "info_bits": "info gain (bits)"}
    print(
        f"{res['submission']}: {res['rooms']} rooms, poses={res['poses']}, threshold={res['threshold']:.3f}"
    )
    for k, v in res["metrics"].items():
        print(
            f"  {names[k]:<17} {v['mean']:8.4f} ± {v['se']:.4f}   baseline {v['baseline']:.4f}   Δ {v['delta']:+.4f} ± {v['delta_se']:.4f}  (z = {v['z']:.1f})"
        )
    if args.json:
        args.json.write_text(json.dumps(res, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
